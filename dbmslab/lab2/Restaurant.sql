
CREATE TABLE RES_CUSTOMER(
CUS_ID CHAR(5) NOT NULL PRIMARY KEY,
CUS_NAME VARCHAR(30) NOT NULL,
CUS_ADDRESS VARCHAR(255),
CUS_PHONE CHAR(10));  

CREATE TABLE RES_BOOKING(
BOOKING_ID CHAR(5) NOT NULL PRIMARY KEY,
CUS_ID CHAR(5) NOT NULL,
BOOKING_DATE DATE DEFAULT SYSDATE,
CONSTRAINT resCusidInBookingAsFK FOREIGN KEY(CUS_ID) REFERENCES RES_CUSTOMER(CUS_ID));


CREATE TABLE RES_STAFF(
EMP_ID CHAR(5) NOT NULL PRIMARY KEY,
EMP_NAME VARCHAR(30) NOT NULL,
EMP_ADDRESS VARCHAR(255),
EMP_PHONE CHAR(10),
EMP_SALARY INTEGER);  



CREATE TABLE RES_TABLE(
TBL_ID CHAR(5) NOT NULL PRIMARY KEY,
BOOKING_ID CHAR(5) NOT NULL,
SERVER_ID CHAR(5) NOT NULL,
CONSTRAINT resBookIdInTableAsFK FOREIGN KEY(BOOKING_ID) REFERENCES RES_BOOKING(BOOKING_ID),
CONSTRAINT resStaffIdInTableAsFK FOREIGN KEY(SERVER_ID) REFERENCES RES_STAFF(EMP_ID));



CREATE TABLE RES_ORDER(
ORD_ID CHAR(5) NOT NULL PRIMARY KEY ,
TBL_NO CHAR(5) NOT NULL,
CONSTRAINT resTableIdInOrderAsFK FOREIGN KEY(TBL_NO) REFERENCES RES_TABLE(TBL_ID));



CREATE TABLE RES_BILLING(
ORD_ID CHAR(5) NOT NULL PRIMARY KEY,
COST INTEGER ,
CONSTRAINT resOrdIdInBillAsFK FOREIGN KEY(ORD_ID) REFERENCES RES_ORDER(ORD_ID));



CREATE TABLE RES_MENU(
SLNO CHAR(3) NOT NULL PRIMARY KEY,
ITM_NAME VARCHAR2(20) NOT NULL,
PRICE INTEGER NOT NULL);


CREATE TABLE RES_INGREDIENT(
SLNO CHAR(3) NOT NULL PRIMARY KEY,
ITM_NAME VARCHAR2(20) NOT NULL,
STOCK INTEGER DEFAULT 0);


CREATE TABLE RES_MENU_INTEGRATION(
MENU_ID CHAR(3) NOT NULL PRIMARY KEY,
INGRED_ID CHAR(3) NOT NULL,
QTY INTEGER,
CONSTRAINT resMenuIdInMenuIntegrationAsFK FOREIGN KEY(MENU_ID) REFERENCES RES_MENU(SLNO),
CONSTRAINT resIngredIdInMenuIntegrationAsFK FOREIGN KEY(INGRED_ID) REFERENCES RES_INGREDIENT(SLNO));


CREATE TABLE RES_ORD_DETAIL(
SLNO CHAR(3) NOT NULL PRIMARY KEY,
ORD_ID CHAR(5) NOT NULL,
MENU_ID CHAR(3) NOT NULL,
QTY INTEGER DEFAULT 1,
CONSTRAINT resOrdIdInOrdDetailAsFk FOREIGN KEY(ORD_ID) REFERENCES RES_ORDER(ORD_ID),
CONSTRAINT resMenuIdInOrdDetailAsFk FOREIGN KEY(MENU_ID) REFERENCES RES_MENU(SLNO));



