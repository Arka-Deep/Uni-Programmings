CREATE TABLE HOS_PATIENT(
    PATIENT_ID CHAR(5) NOT NULL PRIMARY KEY,
    PATIENT_NAME VARCHAR2(30) NOT NULL,
    PATIENT_ADDRESS VARCHAR2(255),
    PATIENT_PH CHAR(10));

CREATE TABLE HOS_HOSPITAL(
    HOSPITAL_CODE CHAR(5) NOT NULL PRIMARY KEY,
    HOSPITAL_NAME VARCHAR2(30) NOT NULL,
    HOSPITAL_ADDRESS VARCHAR2(50) NOT NULL,
    HOSPITAL_PH CHAR(10) NOT NULL);

CREATE TABLE HOS_DOCTOR(
    DOCTOR_ID CHAR(5) NOT NULL PRIMARY KEY,
    DOCTOR_NAME VARCHAR2(30) NOT NULL,
    DOCTOR_ADDRESS VARCHAR2(50) NOT NULL,
    DOCTOR_PH CHAR(10) NOT NULL,
    HOSPITAL_CODE CHAR(5) NOT NULL,
    CONSTRAINT hosCodeInDoctorAsFK FOREIGN KEY(HOSPITAL_CODE) REFERENCES HOS_HOSPITAL(HOSPITAL_CODE));

CREATE TABLE HOS_DISEASE(
    DISEASE_ID CHAR(5) NOT NULL PRIMARY KEY,
    DISEASE_NAME VARCHAR2(30) NOT NULL);

CREATE TABLE HOS_ADMITTED_FOR(
    ADMIT_CODE CHAR(10) NOT NULL PRIMARY KEY,
    ADMITTED_ON DATE DEFAULT SYSDATE,
    PATIENT_ID CHAR(5) NOT NULL,
    DISEASE_ID CHAR(5) NOT NULL,
    DOCTOR_ID CHAR(5) NOT NULL,
    HOSPITAL_CODE CHAR(5) NOT NULL,
    CONSTRAINT hosPatientIDInAdmittedForAsFK FOREIGN KEY(PATIENT_ID) REFERENCES HOS_PATIENT(PATIENT_ID),
    CONSTRAINT hosDiseaseIDInAdmittedForAsFK FOREIGN KEY(DISEASE_ID) REFERENCES HOS_DISEASE(DISEASE_ID),
    CONSTRAINT hosDoctorIDInAdmittedForAsFK FOREIGN KEY(DOCTOR_ID) REFERENCES HOS_DOCTOR(DOCTOR_ID),
    CONSTRAINT hosHospitalCodeInAdmittedForAsFK FOREIGN KEY(HOSPITAL_CODE) REFERENCES HOS_HOSPITAL(HOSPITAL_CODE));

--ALTER TABLE HOS_PATIENT RENAME COLUMN PARIENT_ID TO PATIENT_ID;

CREATE TABLE HOS_BILLING(
    ADMIT_CODE CHAR(10) NOT NULL PRIMARY KEY,
    FINAL_BILL INTEGER ,
    CONSTRAINT hosAdmitCodeinHosBillingAsFK FOREIGN KEY(ADMIT_CODE) REFERENCES HOS_ADMITTED_FOR(ADMIT_CODE));

