CREATE TABLE BANK_CUSTOMER(
    CUSTOMER_ID CHAR(5) NOT NULL PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(30) NOT NULL ,
    CUSTOMER_ADDRESS VARCHAR2(125) NOT NULL,
    CUSTOMER_PH CHAR(10) NOT NULL);

CREATE TABLE BANK_BRANCH(
    BRANCH_CODE CHAR(5) NOT NULL PRIMARY KEY,
    BRANCH_NAME VARCHAR2(30) NOT NULL,
    BRANCH_ADDRESS VARCHAR2(125) NOT NULL,
    BRANCH_PH CHAR(10) NOT NULL);

CREATE TABLE BANK_EMPLOYEE(
    EMP_ID CHAR(5) NOT NULL PRIMARY KEY,
    EMP_NAME VARCHAR2(30) NOT NULL,
    EMP_ADDRESS VARCHAR2(125) NOT NULL,
    EMP_PH CHAR(10) NOT NULL,
    EMP_SALARY INTEGER NOT NULL,
    BRANCH_CODE CHAR(5) NOT NULL,
    CONSTRAINT bankBranchCodeInEmployeeAsFK FOREIGN KEY(BRANCH_CODE) REFERENCES BANK_BRANCH(BRANCH_CODE));

CREATE TABLE BANK_ACCOUNT(
    ACCOUNT_NUMBER CHAR(14) NOT NULL PRIMARY KEY,
    CUSTOMER_ID CHAR(5) NOT NULL,
    BRANCH_CODE CHAR(5) NOT NULL,
    BALANCE INTEGER DEFAULT 0,
    CONSTRAINT bankCusIdInAccountAsFK FOREIGN KEY(CUSTOMER_ID) REFERENCES BANK_CUSTOMER(CUSTOMER_ID),
    CONSTRAINT bankBranchCodeInAccountAsFK FOREIGN KEY(BRANCH_CODE) REFERENCES BANK_BRANCH(BRANCH_CODE));

CREATE TABLE BANK_PRODUCT(
    PD_CODE CHAR(5) NOT NULL PRIMARY KEY,
    PD_NAME VARCHAR2(30) NOT NULL,
    PD_COST INTEGER NOT NULL);


