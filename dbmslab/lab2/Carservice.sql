CREATE TABLE CAR_CUSTOMER(
    CUSTOMER_ID CHAR(5) NOT NULL PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(30) NOT NULL,
    CUSTOMER_ADDRESS VARCHAR2(125),
    CUSTOMER_PH INTEGER);

CREATE TABLE CAR_CAR(
    CAR_REGS_ID CHAR(5) NOT NULL PRIMARY KEY,
    CAR_NAME VARCHAR2(30),
    CUSTOMER_ID CHAR(5) NOT NULL,
    CONSTRAINT carConsumerIdInCarAsFK FOREIGN KEY(CUSTOMER_ID) REFERENCES CAR_CUSTOMER(CUSTOMER_ID));

CREATE TABLE CAR_MECHANIC(
    EMPLOYEE_ID CHAR(5) NOT NULL PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR2(30) NOT NULL,
    EMPLOYEE_PH CHAR(10) NOT NULL,
    EMPLOYEE_SALARY INTEGER);

CREATE TABLE CAR_BOOKING(
    BOOKING_ID CHAR(5) NOT NULL PRIMARY KEY,
    BOOKING_DATE DATE DEFAULT SYSDATE ,
    CUSTOMER_ID CHAR(5) NOT NULL,
    MECHANIC_ID CHAR(5) NOT NULL,
    CONSTRAINT carConsumerIdInBookingAsFK FOREIGN KEY(CUSTOMER_ID) REFERENCES CAR_CUSTOMER(CUSTOMER_ID),
    CONSTRAINT carMechanicIdInBookingAsFK FOREIGN KEY(MECHANIC_ID) REFERENCES CAR_MECHANIC(EMPLOYEE_ID));

CREATE TABLE CAR_TOTAL_CARS(
    REF_UID CHAR(5) NOT NULL PRIMARY KEY,
    CAR_REGS_ID CHAR(5) NOT NULL,
    BOOKING_ID CHAR(5) NOT NULL,
    CONSTRAINT carRegsIdInTotalCarsAsFK FOREIGN KEY(CAR_REGS_ID) REFERENCES CAR_CAR(CAR_REGS_ID),
    CONSTRAINT carBookingIdInTotalCarsAsFK FOREIGN KEY(BOOKING_ID) REFERENCES CAR_BOOKING(BOOKING_ID));

CREATE TABLE CAR_BILLING(
    BOOKING_ID CHAR(5) NOT NULL PRIMARY KEY,
    TOTAL_BILL INTEGER ,
    CONSTRAINT carBookingIdInBillingAsFK FOREIGN KEY(BOOKING_ID) REFERENCES CAR_BOOKING(BOOKING_ID));

