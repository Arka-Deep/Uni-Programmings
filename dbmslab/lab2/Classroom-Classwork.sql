CREATE TABLE CLASS_COURSE(
    ID CHAR(5) NOT NULL PRIMARY KEY,
    COURSE_NAME VARCHAR2(30) NOT NULL,
    COURSE_CREDIT INTEGER DEFAULT 1,
    LAB_EXIST BOOLEAN DEFAULT FALSE,
    COURSE_DESCRIPTION VARCHAR2(125));

CREATE TABLE CLASS_CLASSROOM(
    ROOM_NO CHAR(3) NOT NULL PRIMARY KEY,
    ROOM_NAME VARCHAR2(20),
    SITTNG_CAPACITY INTEGER DEFAULT 60,
    PROJECTOR_AVAILABLE BOOLEAN DEFAULT TRUE);

CREATE TABLE CLASS_SEMESTER(
    SEM_ID CHAR(5) NOT NULL PRIMARY KEY,
    SEM_NAME VARCHAR2(30) ,
    SEM_TYPE VARCHAR2(10));

CREATE TABLE CLASS_TIMETABLE(
    TT_ID CHAR(5) NOT NULL PRIMARY KEY,
    TT_DAY VARCHAR2(12) ,
    TIME_START TIMESTAMP DEFAULT SYSTIMESTAMP,
    TIME_END TIMESTAMP DEFAULT SYSTIMESTAMP);

CREATE TABLE CLASS_SECTION(
    SEC_ID CHAR(5) NOT NULL PRIMARY KEY,
    SEC_NAME VARCHAR2(20) ,
    ADDMISSION_YEAR NUMBER(4) DEFAULT 2026,
    SEC_CAPACITY NUMBER(3) DEFAULT 50);

CREATE TABLE CLASS_COURSE_SEM_RELATION(
    REL_ID CHAR(3) NOT NULL PRIMARY KEY,
    COURSE_ID CHAR(5) NOT NULL,
    SEM_ID CHAR(5) NOT NULL,
    CONSTRAINT classCourseIdInCourseSemRelationAsFK FOREIGN KEY(COURSE_ID) REFERENCES CLASS_COURSE(ID),
    CONSTRAINT classSemIdInCourseSemRelationAsFK FOREIGN KEY(SEM_ID) REFERENCES CLASS_SEMESTER(SEM_ID));

CREATE TABLE CLASS_STUDENT(
    ROLL NUMBER(8) NOT NULL PRIMARY KEY,
    SEC_ID CHAR(5) NOT NULL,
    STUDENT_NAME VARCHAR2(30) NOT NULL,
    SEM_ID CHAR(5) NOT NULL,
    CONSTRAINT classSecIdInStudenAsFK FOREIGN KEY(SEC_ID) REFERENCES CLASS_SECTION(SEC_ID),
    CONSTRAINT classSemIdInStudenAsFK FOREIGN KEY(SEM_ID) REFERENCES CLASS_SEMESTER(SEM_ID));

CREATE TABLE CLASS_FACULTY(
    FAC_ID CHAR(5) NOT NULL PRIMARY KEY,
    EMP_NO NUMBER(8) NOT NULL,
    EMP_NAME VARCHAR2(30) NOT NULL,
    DOB DATE ,
    DOJ DATE);

CREATE TABLE CLASS_TIME_TABLE_REL(
    TT_ID CHAR(5) NOT NULL PRIMARY KEY,
    FAC_ID CHAR(5) NOT NULL,
    COURSE_ID CHAR(5) NOT NULL,
    ROOM_NO CHAR(3) NOT NULL,
    SEC_ID CHAR(5) NOT NULL,
    CONSTRAINT classTimeTableIdInTimeTableRelationAsFK FOREIGN KEY(TT_ID) REFERENCES CLASS_TIMETABLE(TT_ID),
    CONSTRAINT classFacultyIdInTimeTableRelationAsFK FOREIGN KEY(FAC_ID) REFERENCES CLASS_FACULTY(FAC_ID),
    CONSTRAINT classCourseIdInTimeTableRelationAsFK FOREIGN KEY(COURSE_ID) REFERENCES CLASS_COURSE(ID),
    CONSTRAINT classRoomNoInTimeTableRelationAsFK FOREIGN KEY(ROOM_NO) REFERENCES CLASS_CLASSROOM(ROOM_NO),
    CONSTRAINT classSecIdInTimeTableRelationAsFK FOREIGN KEY(SEC_ID) REFERENCES CLASS_SECTION(SEC_ID));

