
CREATE TABLE EMPLOYEE_LAB4 (
    ID INT PRIMARY KEY,
    LAST_NAME VARCHAR(50),
    FIRST_NAME VARCHAR(50),
    MIDDLE_NAME VARCHAR(50),
    FATHER_NAME VARCHAR(100),
    MOTHER_NAME VARCHAR(100),
    SEX CHAR(1),
    HIRE_DATE DATE,
    ADDRESS_ VARCHAR(255),
    CITY VARCHAR(100),
    STATE_ VARCHAR(50),
    ZIP VARCHAR(20),
    PHONE VARCHAR(20),
    PAGER VARCHAR(20)
);

CREATE TABLE SCHOOL_LAB4 (
    ID INT PRIMARY KEY,
    NAME_ VARCHAR(100)
);

CREATE TABLE JOB_LAB4 (
    ID INT PRIMARY KEY,
    NAME_ VARCHAR(100),
    TITLE_ VARCHAR(100),
    SALARY DECIMAL(10, 2),
    BONUS DECIMAL(10, 2)
);


CREATE TABLE EMPLOYEE_ALIGNMENT_LAB4 (
    EMPLOYEE_ID INT ,
    SCHOOL_ID INT ,
    PRIMARY KEY (EMPLOYEE_ID, SCHOOL_ID)
);


CREATE TABLE EMPLOYEE_PAY_LAB4 (
    EMPLOYEE_ID INT ,
    JOB_ID INT,
    PRIMARY KEY (EMPLOYEE_ID, JOB_ID)
);


CREATE TABLE PRODUCT_LAB4 (
    ID INT PRIMARY KEY,
    NAME_ VARCHAR2(100),
    DESCRIPTION_ VARCHAR2(200),
    STATUS_ VARCHAR2(20),
    CREATED_DATE TIMESTAMP,
    CREATED_BY VARCHAR2(50),
    LAST_MODIFIED_DATE TIMESTAMP,
    LAST_MODIFIED_BY VARCHAR2(50),
    COST_ DECIMAL(10, 2),
    INJECTED_DATE DATE
);


